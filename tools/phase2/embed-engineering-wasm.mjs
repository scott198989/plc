import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

import { resolveInProject } from "../foundation/paths.mjs";

const MAX_ENGINEERING_WASM_BYTES = 8 * 1024 * 1024;
const wasmPath = resolveInProject(
  "target",
  "wasm32-unknown-unknown",
  "release",
  "plc_engineering_wasm.wasm",
);
const generatedDirectory = resolveInProject(
  "apps",
  "foundation-shell",
  "src",
  "generated",
);
const generatedPath = path.join(generatedDirectory, "plc-engineering-wasm.ts");

const wasm = await readFile(wasmPath);
if (
  wasm.byteLength < 8 ||
  !wasm.subarray(0, 8).equals(Buffer.from([0, 97, 115, 109, 1, 0, 0, 0]))
) {
  throw new Error("The compiled engineering artifact is not a WebAssembly 1.0 module.");
}
if (wasm.byteLength > MAX_ENGINEERING_WASM_BYTES) {
  throw new Error(
    `Engineering WASM exceeds ${MAX_ENGINEERING_WASM_BYTES} bytes: ${wasm.byteLength} bytes.`,
  );
}

const module = new WebAssembly.Module(wasm);
const imports = WebAssembly.Module.imports(module);
if (imports.length !== 0) {
  throw new Error(`Engineering WASM must have zero imports: ${JSON.stringify(imports)}`);
}
const requiredExports = [
  "foundation_health",
  "foundation_health_len",
  "memory",
  "plc_input_prepare",
  "plc_output_length",
  "plc_output_pointer",
  "plc_session_abort_save",
  "plc_session_commit_save",
  "plc_session_create",
  "plc_session_handle",
  "plc_session_open",
  "plc_session_prepare_save",
];
const exportNames = new Set(WebAssembly.Module.exports(module).map(({ name }) => name));
for (const required of requiredExports) {
  if (!exportNames.has(required)) {
    throw new Error(`Engineering WASM is missing export: ${required}`);
  }
}

const sha256 = createHash("sha256").update(wasm).digest("hex").toUpperCase();
const source = `// Generated by tools/phase2/embed-engineering-wasm.mjs. Do not edit.\n` +
  `export const ENGINEERING_WASM_SHA256 = ${JSON.stringify(sha256)} as const;\n` +
  `export const ENGINEERING_WASM_BASE64 = ${JSON.stringify(wasm.toString("base64"))} as const;\n`;

await mkdir(generatedDirectory, { recursive: true });
await writeFile(generatedPath, source, { encoding: "utf8", flag: "w" });
console.log(JSON.stringify({ bytes: wasm.byteLength, imports: 0, sha256 }));
